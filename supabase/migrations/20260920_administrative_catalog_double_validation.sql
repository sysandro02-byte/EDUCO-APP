language plpgsql security definer set search_path=''
as $$
declare r public.administrative_catalog_change_requests;
begin
  if auth.uid() is null then raise exception 'Authentification requise'; end if;
  select * into r from public.administrative_catalog_change_requests where id=p_request_id for update;
  if r.id is null or r.status<>'DRAFT' or r.created_by<>auth.uid() then raise exception 'Brouillon non annulable'; end if;
