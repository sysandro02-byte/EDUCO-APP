create or replace function private.list_catalog_change_history_secure(p_service_code text)
returns table(
  event_id bigint,request_id uuid,action text,note text,created_at timestamptz,
  actor_uid uuid,actor_name text,request_status text
)
language plpgsql security definer set search_path='' stable
as $$
declare s public.administrative_services;
begin
  select * into s from public.administrative_services where code=p_service_code;
  if s.code is null then raise exception 'Démarche introuvable'; end if;
  if not (private.can_edit_catalog_secure(s.ministry) or private.can_control_catalog_secure(s.ministry) or private.can_final_approve_catalog_secure(s.ministry)) then
    raise exception 'Accès non autorisé';
  end if;

  return query
  select e.id,e.request_id,e.action,e.note,e.created_at,e.actor_uid,u.name,r.status
  from public.administrative_catalog_change_events e
  join public.administrative_catalog_change_requests r on r.id=e.request_id
  left join public.users u on u.uid=e.actor_uid::text
  where e.service_code=p_service_code
  order by e.created_at desc
  limit 100;
end $$;
