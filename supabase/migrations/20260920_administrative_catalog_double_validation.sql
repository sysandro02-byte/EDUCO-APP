create table if not exists public.administrative_catalog_change_requests (
  id uuid primary key default gen_random_uuid(),
  service_code text not null references public.administrative_services(code) on delete cascade,
  ministry text not null,
  status text not null default 'DRAFT'
    check (status in ('DRAFT','SUBMITTED','CONTROL_APPROVED','APPLIED','REJECTED','CANCELLED')),
  version_base integer not null,
  before_snapshot jsonb not null,
  proposed_service jsonb not null,
  proposed_form_fields jsonb not null default '[]'::jsonb,
  proposed_required_documents jsonb not null default '[]'::jsonb,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  submitted_at timestamptz,
  control_approved_by uuid references auth.users(id),
  control_approved_at timestamptz,
  final_approved_by uuid references auth.users(id),
  final_approved_at timestamptz,
  rejected_by uuid references auth.users(id),
  rejection_note text,
  applied_at timestamptz
);
alter table public.administrative_catalog_change_requests enable row level security;
revoke all on public.administrative_catalog_change_requests from anon,authenticated;

create unique index if not exists administrative_catalog_one_open_request_per_service
on public.administrative_catalog_change_requests(service_code)
where status in ('DRAFT','SUBMITTED','CONTROL_APPROVED');

create index if not exists administrative_catalog_change_requests_ministry_idx
on public.administrative_catalog_change_requests(ministry,status,created_at desc);

create table if not exists public.administrative_catalog_change_events (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.administrative_catalog_change_requests(id) on delete cascade,
  service_code text not null,
  ministry text not null,
  action text not null check (action in (
    'DRAFT_CREATED','DRAFT_UPDATED','SUBMITTED','CONTROL_APPROVED',
    'FINAL_APPROVED','REJECTED','CANCELLED','APPLIED'
  )),
  actor_uid uuid not null references auth.users(id),
  note text,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.administrative_catalog_change_events enable row level security;
revoke all on public.administrative_catalog_change_events from anon,authenticated;

create index if not exists administrative_catalog_change_events_request_idx
on public.administrative_catalog_change_events(request_id,created_at);

create or replace function private.catalog_actor_role_secure(p_ministry text)
returns text
language sql
security definer
set search_path=''
stable
as $$
 select upper(replace(replace(trim(u.role),' ','_'),'-','_'))
 from public.users u
 join public.administrative_government_accounts g on g.user_uid=auth.uid()
 where u.uid=auth.uid()::text
   and g.active
   and g.ministry=upper(trim(p_ministry))
   and lower(coalesce(u.status,'actif')) not in ('inactif','inactive','suspendu','suspended')
 limit 1
$$;
revoke all on function private.catalog_actor_role_secure(text) from public,anon;
grant execute on function private.catalog_actor_role_secure(text) to authenticated;

